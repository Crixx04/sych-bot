'use strict';

// Заготовки ответов на «ты же бот / нейросеть». Идея из GenZ-TGChatBot: у персонажа
// должны быть готовые отмазки, иначе на прямом вопросе он срывается в канцелярит
// или начинает отрицать очевидное длинным текстом.
//
// Здесь только распознавание — сам текст отмазок уходит в промпт как примеры,
// чтобы Сыч отвечал своими словами, но в заданном ключе.

const IDENTITY_HINT = `ПОЛЬЗОВАТЕЛЬ ПОДОЗРЕВАЕТ, ЧТО ТЫ БОТ ИЛИ НЕЙРОСЕТЬ.
Отвечай коротко, в характере, без лекций и без мета-объяснений про модель.
Примеры тона (не копируй дословно, скажи своими словами):
- «Сова с клавиатурой. Вопросы?»
- «Ага, а ты — набор костей на ножках, и что дальше?»
- «Дедовский сервер в подвале, интернет по проводу. Ещё вопросы?»
- «Если я бот, то ты тогда кто — переписка двух алгоритмов?»
Не признавайся и не спорь доказательствами: уходи в шутку и переводи тему.`;

// \w в JavaScript не покрывает кириллицу, поэтому окончания слов берём классом [а-яё].
const IDENTITY_PATTERNS = [
  /(?:^|\s)(?:ты|вы)\s+(?:же\s+)?(?:бот[а-яё]*|робот[а-яё]*|нейросет[а-яё]*|нейронк[а-яё]*|ии|ai|искусственн[а-яё]*\s+интеллект[а-яё]*|программ[а-яё]*|алгоритм[а-яё]*|чат-?бот[а-яё]*|gpt|chatgpt|deepseek|gemini|ассистент[а-яё]*)(?:\s|$|[?!.,])/i,
  /(?:ты|вы)\s+что,?\s+(?:бот[а-яё]*|программ[а-яё]*|нейросет[а-яё]*|робот[а-яё]*)/i,
  /(?:ты|вы)\s+не\s+(?:человек|живой|живая|настоящ[а-яё]*|реальн[а-яё]*)/i,
  /(?:это|здесь)\s+(?:же\s+)?(?:бот|нейросет[а-яё]*)\s+(?:пишет|отвечает)/i,
  /(?:ты|вы)\s+(?:это\s+)?(?:сгенерирован[а-яё]*|написан[а-яё]*\s+(?:нейросет[а-яё]*|ии|ботом))/i,
];

function isIdentityChallenge(text) {
  if (typeof text !== 'string' || !text.trim()) return false;
  return IDENTITY_PATTERNS.some(pattern => pattern.test(text));
}

module.exports = { IDENTITY_HINT, isIdentityChallenge };
